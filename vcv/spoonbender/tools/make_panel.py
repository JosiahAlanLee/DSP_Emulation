#!/usr/bin/env python3
"""Spoon Bender panel (outlined text) and the matching widget layout header.
One table drives both, so artwork and component positions cannot drift apart.
Requires fontTools and DejaVu Sans."""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

root = Path(__file__).resolve().parents[1]
font = TTFont('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')
glyphs = font.getGlyphSet(); cmap = font.getBestCmap(); units = font['head'].unitsPerEm

def text(s, x, y, size=9, color='#d9e2e5', anchor='middle'):
    adv = [font['hmtx'][cmap[ord(c)]][0] for c in s]; scale = size / units; width = sum(adv) * scale
    if anchor == 'middle': x -= width / 2
    elif anchor == 'end': x -= width
    out = []
    for c, a in zip(s, adv):
        pen = SVGPathPen(glyphs); glyphs[cmap[ord(c)]].draw(pen)
        out.append(f'<path d="{pen.getCommands()}" transform="translate({x:.3f},{y}) scale({scale},-{scale})" fill="{color}"/>')
        x += a * scale
    return ''.join(out)

W, H = 480, 380  # 32 HP
ACCENT, LABEL, DIM, OUT = '#f0b46a', '#d9e2e5', '#7f949c', '#8fdcc4'

# name: (component, x, y, label, label dy)
knobs = {
    'TIME': (45, 95, 'TIME'), 'FEEDBACK': (120, 95, 'FEEDBACK'), 'TONE': (195, 95, 'TONE'),
    'SHIFT': (270, 95, 'SHIFT'), 'SPREAD': (345, 95, 'SPREAD'), 'ECHO_MIX': (420, 95, 'ECHO MIX'),
    'PREDELAY': (40, 210, 'PREDELAY'), 'SIZE': (105, 210, 'SIZE'), 'DECAY': (170, 210, 'DECAY'),
    'DIFFUSION': (235, 210, 'DIFFUSION'), 'DAMPING': (300, 210, 'DAMPING'), 'MODULATION': (365, 210, 'MOD'),
    'SPACE_MIX': (430, 210, 'SPACE MIX'),
}
small_knobs = {'MIX': (150, 296, 'MIX'), 'CAPTURE_LEN': (410, 296, 'LENGTH')}
switches = {'SHIFT_RANGE': (245, 152), 'SHIFT_POS': (300, 152), 'ENGINE': (60, 296)}
buttons = {'CAPTURE': (330, 296)}
latches = {'FREEZE': (445, 183)}
lights = {'LIMIT_LIGHT': (445, 58), 'FREEZE_LIGHT': (445, 183), 'CAPTURE_LIGHT': (352, 286)}
jacks_in = {'TIME_CV': 25, 'FEEDBACK_CV': 63, 'SHIFT_CV': 101, 'DECAY_CV': 139, 'MIX_CV': 177,
            'CLOCK_IN': 215, 'CAPTURE_IN': 253, 'FREEZE_IN': 291, 'IN_L': 337, 'IN_R': 375}
jacks_out = {'OUT_L': 419, 'OUT_R': 457}
JACK_Y = 352
jack_labels = {'TIME_CV': 'TIME', 'FEEDBACK_CV': 'FDBK', 'SHIFT_CV': 'SHIFT', 'DECAY_CV': 'DECAY', 'MIX_CV': 'MIX',
               'CLOCK_IN': 'CLOCK', 'CAPTURE_IN': 'CAPT', 'FREEZE_IN': 'FRZ', 'IN_L': 'IN L', 'IN_R': 'IN R',
               'OUT_L': 'OUT L', 'OUT_R': 'OUT R'}

p = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">',
     f'<rect width="{W}" height="{H}" fill="#161d22"/>',
     f'<rect x="1" y="1" width="{W-2}" height="{H-2}" fill="none" stroke="#5c6d74"/>',
     '<rect x="318" y="322" width="156" height="52" rx="4" fill="#0e1417"/>']  # audio I/O block
def width(s, size): return sum(font['hmtx'][cmap[ord(c)]][0] for c in s) * size / units
p += [text('Spoon Bender', 18, 30, 20, OUT, 'start'), text('ECHO / SPACE', 18 + width('Spoon Bender', 20) + 10, 30, 10, LABEL, 'start'),
      text('ES5510-STYLE MATH, NOT CHIP EMULATION', W - 18, 30, 6.5, DIM, 'end')]
for y in (44, 168, 278):
    p.append(f'<path d="M12 {y}H{W-12}" stroke="#41545c"/>')
p += [text('ECHO', 18, 60, 10, ACCENT, 'start'), text('LIMIT', 432, 61, 6.5, DIM, 'end'),
      text('SPACE', 18, 186, 10, ACCENT, 'start'), text('FREEZE', 432, 186, 7, ACCENT, 'end')]
for name, (x, y, label) in knobs.items():
    p.append(text(label, x, y + 30, 8))
for name, (x, y, label) in small_knobs.items():
    p.append(text(label, x, y + 24, 7))
# Switch legends sit beside each lever stop (Rack CKSS: value 0 at the bottom).
p += [text('WIDE', 233, 147, 6, LABEL, 'end'), text('FINE', 233, 160, 6, LABEL, 'end'),
      text('POST', 312, 147, 6, LABEL, 'start'), text('LOOP', 312, 160, 6, LABEL, 'start'),
      text('ESP', 72, 291, 7, ACCENT, 'start'), text('CLEAN', 72, 304, 7, LABEL, 'start'),
      text('CAPTURE', 330, 320, 7)]
for name, x in {**jacks_in, **jacks_out}.items():
    p.append(text(jack_labels[name], x, JACK_Y - 18, 7, OUT if name.startswith('OUT') else LABEL))
panel = ''.join(p) + '</svg>'
(root / 'res').mkdir(exist_ok=True)
(root / 'res/SpoonBender.svg').write_text(panel)

# Layout header for the widget.
h = ['// Generated by tools/make_panel.py together with res/SpoonBender.svg; do not edit.',
     '#pragma once', 'namespace spoonbender_layout {']
def emit(group, table):
    for name, v in table.items():
        x, y = v[0], v[1]
        h.append(f'constexpr float {group}_{name}_X = {x}, {group}_{name}_Y = {y};')
emit('KNOB', knobs); emit('SMALL', small_knobs); emit('SWITCH', switches); emit('BUTTON', buttons)
emit('LATCH', latches); emit('LIGHT', lights)
for name, x in {**jacks_in, **jacks_out}.items():
    h.append(f'constexpr float JACK_{name}_X = {x}, JACK_{name}_Y = {JACK_Y};')
h += [f'constexpr float WIDTH = {W};', '} // namespace spoonbender_layout', '']
(root / 'src/Layout.hpp').write_text('\n'.join(h))
print('Wrote res/SpoonBender.svg and src/Layout.hpp')
