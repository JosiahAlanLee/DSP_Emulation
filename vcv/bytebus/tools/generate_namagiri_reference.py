#!/usr/bin/env python3
"""Generate Namagiri reference vectors: convergents and the note pattern.

Runs HydraPy's namagiri.convergents and namagiri_pattern.pattern from HydraPy
main (PRs #93 and #94) with numpy, for a grid of q (radii 0, .05, .5, .9, .97;
several angles) at depths 1..32, and writes
- tests/namagiri_reference.h: the convergents plus convergent_controls
  (magnitude, phase, delta), and
- tests/namagiri_pattern_reference.h: per-step velocity and note for several
  root/span/threshold settings (rests are velocity < threshold).
`--check` regenerates both and compares without touching the files.

Run from a checkout of DSP_Emulation with the hydrapy conda env active
(numpy needed), or point --namagiri/--pattern at checked-out copies:

    python3 vcv/bytebus/tools/generate_namagiri_reference.py --check
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'tests' / 'namagiri_reference.h'
PATTERN_OUT = ROOT / 'tests' / 'namagiri_pattern_reference.h'
HYDRAPY = Path.home() / 'dev' / 'hydrapy-claude'
BRANCH = 'origin/main'                          # PRs #93 and #94 are merged on main
FILE = 'hydrapy/namagiri.py'
PATTERN_FILE = 'hydrapy/namagiri_pattern.py'
PATTERN_ROOTS = [0, 48]
PATTERN_SPANS = [1, 24, 96]
PATTERN_THRESHOLDS = [0.0, 0.1, 0.5]

RADII = [0.0, 0.05, 0.5, 0.9, 0.97]
ANGLES = [0.0, 0.25, 0.5, 0.75, 0.37]       # turns
DEPTHS = list(range(1, 33))


def cpp_double(x):
    return f'{float(x):.17g}'


def pattern_header(commit, rows):
    settings = len(PATTERN_ROOTS) * len(PATTERN_SPANS) * len(PATTERN_THRESHOLDS)
    points = len(RADII) * len(ANGLES)
    lines = ['// Generated by tools/generate_namagiri_reference.py; do not edit.',
             f'// HydraPy namagiri_pattern.py at {commit} (main), evaluated with numpy.',
             '// Per setting s (root = ROOTS[s / 3 / 3], span = SPANS[s / 3 % 3],',
             '// threshold = THRESHOLDS[s % 3]) and q point c: for n = 1..32,',
             f'// DATA[((s * {points} + c) * 32 + n) * 2 + 0]: velocity (clip(delta/(1+delta))),',
             '// DATA[((s * CASES + c) * 32 + n) * 2 + 1]: note (0 for rests, i.e. velocity < threshold).',
             '// Parity tolerance in tests: 1e-9 on velocity; notes and rests exact.',
             '#pragma once', '#include <cstddef>',
             'namespace namagiri_pattern_reference {',
             'constexpr int ROOTS[] = {%s};' % ', '.join(map(str, PATTERN_ROOTS)),
             'constexpr int SPANS[] = {%s};' % ', '.join(map(str, PATTERN_SPANS)),
             'constexpr double THRESHOLDS[] = {%s};' % ', '.join(cpp_double(v) for v in PATTERN_THRESHOLDS),
             f'constexpr size_t SETTINGS = {settings};',
             f'constexpr size_t CASES = {points};',
             f'constexpr size_t DEPTH = 32;',
             'constexpr double DATA[] = {']
    for row in rows:
        lines.append('    ' + ', '.join(cpp_double(v) for v in row) + ',')
    lines += ['};', '} // namespace namagiri_pattern_reference', '']
    return '\n'.join(lines)


def header(commit, cases, points):
    lines = ['// Generated by tools/generate_namagiri_reference.py; do not edit.',
             f'// HydraPy namagiri.py at {commit} (branch {BRANCH}), evaluated with numpy.',
             '// Each case: radius, turns, then for n = 1..32: R.re, R.im, mag, phase, delta',
             '// (convergent_controls; delta[0] is 0 as in HydraPy). Grid: radii %s,' % RADII,
             f'// angles {ANGLES} (turns), depths 1..32. Parity tolerance in tests: 1e-9.',
             '#pragma once', '#include <cstddef>',
             'namespace namagiri_reference {',
             f'constexpr size_t CASES = {points};',
             f'constexpr size_t DEPTH = {len(cases) // points};',
             '// DATA[(case * DEPTH + n) * 7 + 0..1]: radius, turns of case row n=0;',
             '// DATA[(case * DEPTH + n) * 7 + 2..6]: R_n.re, R_n.im, mag, phase, delta.',
             'constexpr double DATA[] = {']
    for c in cases:
        lines.append('    ' + ', '.join(cpp_double(v) for v in c) + ',')
    lines += ['};', '} // namespace namagiri_reference', '']
    return '\n'.join(lines)


def load_module(text, name, package):
    import sys
    if package not in sys.modules:                  # the relative import's anchor
        parent = importlib.util.module_from_spec(
            importlib.util.spec_from_loader(package, loader=None))
        parent.__path__ = []
        sys.modules[package] = parent
    spec = importlib.util.spec_from_loader(f'{package}.{name}', loader=None)
    module = importlib.util.module_from_spec(spec)
    sys.modules[f'{package}.{name}'] = module
    exec(compile(text, f'{name}.py', 'exec'), module.__dict__)
    return module


def hydrapy_modules(namagiri_override, pattern_override):
    """hydrapy.namagiri and hydrapy.namagiri_pattern from HydraPy main (or files)."""
    def from_git(path):
        try:
            return subprocess.run(['git', '-C', str(HYDRAPY), 'show', f'{BRANCH}:{path}'],
                                  capture_output=True, check=True).stdout.decode()
        except (subprocess.CalledProcessError, FileNotFoundError):
            return (HYDRAPY / path).read_text()     # no local ref: the checked-out file
    namagiri_text = Path(namagiri_override).read_text() if namagiri_override else from_git(FILE)
    pattern_text = Path(pattern_override).read_text() if pattern_override else from_git(PATTERN_FILE)
    namagiri = load_module(namagiri_text, 'namagiri', 'hydrapy')
    pattern = load_module(pattern_text, 'namagiri_pattern', 'hydrapy')
    return namagiri, pattern


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare against the committed files')
    parser.add_argument('--namagiri', help='path to a checked-out hydrapy/namagiri.py')
    parser.add_argument('--pattern', help='path to a checked-out hydrapy/namagiri_pattern.py')
    args = parser.parse_args()
    import numpy as np

    namagiri, pattern = hydrapy_modules(args.namagiri, args.pattern)
    if args.namagiri or args.pattern:
        commit = 'file'
    else:
        commit = subprocess.run(['git', '-C', str(HYDRAPY), 'rev-parse', BRANCH],
                                capture_output=True, check=True).stdout.decode().strip()

    cases = []
    for r in RADII:
        for t in ANGLES:
            q = complex(r * np.cos(2 * np.pi * t), r * np.sin(2 * np.pi * t))
            values = namagiri.convergents(q, 32)
            controls = namagiri.convergent_controls(q, 32)
            for n in range(32):
                z = values[n]
                cases.append([r, t, z.real, z.imag,
                              controls['magnitude'][n], controls['phase'][n],
                              controls['delta'][n]])
    text = header(commit, cases, len(RADII) * len(ANGLES))

    pattern_rows = []
    for root in PATTERN_ROOTS:
        for span in PATTERN_SPANS:
            for threshold in PATTERN_THRESHOLDS:
                for r in RADII:
                    for t in ANGLES:
                        q = complex(r * np.cos(2 * np.pi * t), r * np.sin(2 * np.pi * t))
                        events = {e.step: e for e in pattern.pattern(
                            q, steps=32, root=root, span=span, threshold=threshold)}
                        controls = namagiri.convergent_controls(q, 32)
                        for n in range(32):
                            change = float(controls['delta'][n])
                            velocity = float(np.clip(change / (1 + change), 0, 1))
                            event = events.get(n)
                            note = event.note if event else 0
                            pattern_rows.append([velocity, note])
    pattern_text = pattern_header(commit, pattern_rows)
    if args.check:
        ok = OUT.read_text() == text and PATTERN_OUT.read_text() == pattern_text
        if ok:
            print(f'OK: both reference headers match (from {commit})')
            return 0
        print(f'MISMATCH: a reference header differs from a fresh generation (from {commit})')
        return 1
    OUT.write_text(text)
    PATTERN_OUT.write_text(pattern_text)
    print(f'Wrote {OUT.name} and {PATTERN_OUT.name} (from {commit})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
