#!/usr/bin/env python3
"""Generate tests/namagiri_reference.h: Namagiri convergent reference vectors.

Runs HydraPy's namagiri.convergents (PR #93, branch feature/namagiri-convergents)
from a temp checkout with numpy, for a grid of q (radii 0, .05, .5, .9, .97;
several angles) at depths 1..32, and writes the convergents plus the
convergent_controls (magnitude, phase, delta) as C++ doubles, with the source
commit recorded. `--check` regenerates and compares without touching the file.

Run from a checkout of DSP_Emulation with the hydrapy conda env active
(numpy + fontTools not needed here), or point --namagiri at a checked-out copy:

    python3 vcv/bytebus/tools/generate_namagiri_reference.py --check
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'tests' / 'namagiri_reference.h'
HYDRAPY = Path.home() / 'dev' / 'hydrapy-claude'
BRANCH = 'origin/feature/namagiri-convergents'
FILE = 'hydrapy/namagiri.py'

RADII = [0.0, 0.05, 0.5, 0.9, 0.97]
ANGLES = [0.0, 0.25, 0.5, 0.75, 0.37]       # turns
DEPTHS = list(range(1, 33))


def cpp_double(x):
    return f'{float(x):.17g}'


def header(commit, cases, points):
    lines = ['// Generated by tools/generate_namagiri_reference.py; do not edit.',
             f'// HydraPy namagiri.py at {commit} (branch {BRANCH}), evaluated with numpy.',
             '// Each case: radius, turns, then for n = 1..32: R.re, R.im, mag, phase, delta',
             '// (convergent_controls; delta[0] is 0 as in HydraPy). Grid: radii %s,' % RADII,
             f'// angles {ANGLES} (turns), depths 1..32. Parity tolerance in tests: 1e-9.',
             '#pragma once', '#include <cstddef>',
             'namespace namagiri_reference {',
             f'constexpr size_t CASES = {points};',
             f'constexpr size_t DEPTH = {len(cases) // points};',
             '// DATA[(case * DEPTH + n) * 7 + 0..1]: radius, turns of case row n=0;',
             '// DATA[(case * DEPTH + n) * 7 + 2..6]: R_n.re, R_n.im, mag, phase, delta.',
             'constexpr double DATA[] = {']
    for c in cases:
        lines.append('    ' + ', '.join(cpp_double(v) for v in c) + ',')
    lines += ['};', '} // namespace namagiri_reference', '']
    return '\n'.join(lines)


def load_namagiri(text):
    module = importlib.util.module_from_spec(
        importlib.util.spec_from_loader('namagiri', loader=None))
    exec(compile(text, 'namagiri.py', 'exec'), module.__dict__)
    return module


def reference_text(override):
    if override:
        return Path(override).read_text()
    return subprocess.run(['git', '-C', str(HYDRAPY), 'show', f'{BRANCH}:{FILE}'],
                          capture_output=True, check=True).stdout.decode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare against the committed file')
    parser.add_argument('--namagiri', help='path to a checked-out hydrapy/namagiri.py')
    args = parser.parse_args()
    import numpy as np

    text = reference_text(args.namagiri)
    if args.namagiri:
        commit = 'file:' + hashlib.sha256(text.encode()).hexdigest()[:16]
    else:
        commit = subprocess.run(['git', '-C', str(HYDRAPY), 'rev-parse', BRANCH],
                                capture_output=True, check=True).stdout.decode().strip()
    namagiri = load_namagiri(text)

    cases = []
    for r in RADII:
        for t in ANGLES:
            q = complex(r * np.cos(2 * np.pi * t), r * np.sin(2 * np.pi * t))
            values = namagiri.convergents(q, 32)
            controls = namagiri.convergent_controls(q, 32)
            for n in range(32):
                z = values[n]
                cases.append([r, t, z.real, z.imag,
                              controls['magnitude'][n], controls['phase'][n],
                              controls['delta'][n]])
    text = header(commit, cases, len(RADII) * len(ANGLES))
    if args.check:
        if OUT.read_text() == text:
            print(f'OK: {OUT.name} matches (from {commit})')
            return 0
        print(f'MISMATCH: {OUT.name} differs from a fresh generation (from {commit})')
        return 1
    OUT.write_text(text)
    print(f'Wrote {OUT.name}: {len(cases) // 32} q points x 32 depths (from {commit})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
