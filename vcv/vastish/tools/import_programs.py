#!/usr/bin/env python3
"""Recreate native parameter metadata/programs from the authoritative Pd generator."""
import contextlib, io, json, pathlib, runpy, sys, tempfile
root = pathlib.Path(__file__).resolve().parents[3]
with tempfile.TemporaryDirectory() as tmp, contextlib.redirect_stdout(io.StringIO()):
    old = sys.argv
    sys.argv = ['gen_vastish.py', tmp]
    pd = runpy.run_path(str(root / 'pd/vastish/tools/gen_vastish.py'))
    sys.argv = old
names = list(pd['defaults']())
# Keep actual generator order; enum names shield the engine from ordering changes.
fnames = ['NONE'] + [f[0] for f in pd['FUNCS']]
# Native-only extensions, appended so saved patches keep their indices:
# FUN 3/4 as K2000-style extra function blocks, AUX 1-4 as polyphonic CV inputs.
sources = pd['SOURCES'] + ['FUN3', 'FUN4', 'AUX1', 'AUX2', 'AUX3', 'AUX4', 'BUS A', 'BUS B', 'LANE A', 'LANE B', 'ONE']
native_params = ['fun3-a', 'fun3-b', 'fun3-eq', 'fun4-a', 'fun4-b', 'fun4-eq']
native_params += ['bus-out-mode', 'bus-out-source', 'fun1-bit', 'fun2-bit', 'fun3-bit', 'fun4-bit']
# SAMPLE is a native-only addition (not in the Pd patch): plays the loaded WAV,
# K2000-style, as the oscillator feeding F1-F3.
waves = ['SAW', 'PULSE', 'TRI', 'COSINE', 'NOISE', 'SAMPLE', 'BUS']
shapes = ['COSINE', 'TRI', 'SAW', 'SQUARE', 'S&H']
eqs = ['A+B','A-B','A*B','(A+B)/2','MAX','MIN','ABS(A-B)','A*(B+1)/2']
algs = [v[0] for v in pd['ALGS'].values()]
names += native_params
def ident(n): return n.replace('-', '_').upper()
def spec(n):
    opts = []
    lo, hi = -128, 135
    if n == 'bus-out-mode': lo, hi, opts = 0, 2, ['Neutral (80)', 'WORD', 'LANES']
    elif n == 'bus-out-source': lo, hi, opts = 0, len(sources)+1, sources + ['DSP', 'MIX']
    elif n.endswith('-bit'): lo, hi, opts = 0, 1, ['Numeric', 'BIT (finite positive)']
    elif n == 'alg': lo, hi, opts = 1, 6, algs
    elif n == 'master': lo, hi = -60, 24
    elif n.endswith('-wave'): lo, hi, opts = 0,len(waves)-1,waves
    elif n.endswith('-pw'): lo, hi = .01,.99
    elif n.endswith('-type'): lo, hi, opts = 0,14,fnames
    elif n.endswith(('-s1','-s2')) or n.startswith('fun') and n.endswith(('-a','-b')): lo,hi,opts = 0,len(sources)-1,sources
    elif n.endswith('-eq'): lo,hi,opts = 0,7,eqs
    elif n.endswith('-shape'): lo,hi,opts = 0,4,shapes
    elif n.endswith('-rate'): lo,hi = .01,100
    elif n.endswith('-kt'): lo,hi = -4,4
    elif n.endswith('-vt'): lo,hi = -100,100
    elif n in ('pan-adj',): lo,hi = -1,1
    elif n.endswith('-b'): lo,hi = -.98,40
    elif n.startswith(('env2-','env3-')) or n in ('amp-a','amp-d','amp-s','amp-r'):
        lo,hi = (0,1) if n.endswith('-s') else (0,10000)
    return lo,hi,opts
lines = ['// Generated by tools/import_programs.py from pd/vastish; do not edit.', '#pragma once', '#include <array>', '#include <string>', '#include <vector>', 'namespace vastish {', 'enum ParamId {']
lines += [f'    {ident(n)} = {i},' for i,n in enumerate(names)]
lines += [f'    PARAM_COUNT = {len(names)}', '};', 'struct ParamInfo { const char* name; float lo, hi; std::vector<std::string> options; };', 'inline const std::array<ParamInfo, PARAM_COUNT>& metadata() {', '    static const std::array<ParamInfo, PARAM_COUNT> table{{']
for n in names:
    lo,hi,opts = spec(n)
    lines += ['        {'+json.dumps(n)+f', {lo}, {hi}, {{'+','.join(json.dumps(o) for o in opts)+'}},']
lines += ['    }}; return table;', '}', f'constexpr int SOURCE_COUNT = {len(sources)};', 'using Parameters = std::array<float, PARAM_COUNT>;', 'inline const std::array<Parameters,6>& programs() {', '    static const std::array<Parameters,6> table{{']
for _, overrides in pd['PROGRAMS']:
    vals = pd['defaults'](); vals.update(overrides)
    for n in native_params: vals.setdefault(n, 0)
    vals['bus-out-mode'] = 1
    vals['bus-out-source'] = len(sources)
    lines += ['        {{'+','.join(str(vals[n]) for n in names)+'}},']
lines += ['    }}; return table;', '}', 'static constexpr const char* programNames[] = {'+','.join(json.dumps(n) for n,_ in pd['PROGRAMS'])+'};', 'static constexpr float routes[6][9] = {']
for _,coef in pd['ALGS'].values(): lines += ['    {'+','.join(str(x) for x in coef)+'},']
lines += ['};', '} // namespace vastish', '']
(root / 'vcv/vastish/src/engine/Programs.hpp').write_text('\n'.join(lines))
print(f'Imported {len(names)} parameters, six programs, six algorithms.')
