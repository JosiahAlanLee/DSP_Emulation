#!/usr/bin/env python3
"""Séance panels (outlined text) for the core and five expanders, and the matching
widget layout header. One table per module drives both, so artwork and component positions
cannot drift apart. Requires fontTools and DejaVu Sans."""
from pathlib import Path
import sys

from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'shared' / 'glyphs'))
from glyph import glyph  # the twelve marks (Clavicula Matricis, Tabula XIII)

font = TTFont('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')
glyphs = font.getGlyphSet(); cmap = font.getBestCmap(); units = font['head'].unitsPerEm


def width(s, size):
    return sum(font['hmtx'][cmap[ord(c)]][0] for c in s) * size / units


def text(s, x, y, size=9, color='#d9e2e5', anchor='middle'):
    scale = size / units
    if anchor == 'middle': x -= width(s, size) / 2
    elif anchor == 'end': x -= width(s, size)
    out = []
    for c in s:
        pen = SVGPathPen(glyphs); glyphs[cmap[ord(c)]].draw(pen)
        out.append(f'<path d="{pen.getCommands()}" transform="translate({x:.3f},{y}) scale({scale},-{scale})" fill="{color}"/>')
        x += font['hmtx'][cmap[ord(c)]][0] * scale
    return ''.join(out)


H = 380
ACCENT, LABEL, DIM, OUT = '#f0b46a', '#d9e2e5', '#7f949c', '#8fdcc4'
BG, EDGE, RULE, BLOCK = '#161d22', '#5c6d74', '#41545c', '#0e1417'
header = ['// Generated by tools/make_panel.py together with res/*.svg; do not edit.', '#pragma once',
          'namespace seance_layout {']


def emit(ns, groups, w):
    header.append(f'namespace {ns} {{')
    for prefix, table in groups:
        for name, v in table.items():
            header.append(f'constexpr float {prefix}_{name}_X = {v[0]}, {prefix}_{name}_Y = {v[1]};')
    header.append(f'constexpr float WIDTH = {w};')
    header.append(f'}} // namespace {ns}')


def frame(w):
    return [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{H}" viewBox="0 0 {w} {H}">',
            f'<rect width="{w}" height="{H}" fill="{BG}"/>',
            f'<rect x="1" y="1" width="{w-2}" height="{H-2}" fill="none" stroke="{EDGE}"/>']


# ---------------------------------------------------------------- core (10 HP)
W = 150
knobs = {'SIZE': (40, 118, 'SIZE'), 'SEED': (110, 118, 'SEED'), 'MIX': (40, 196, 'MIX')}
buttons = {'RESET': (110, 196)}
lights = {'CHAIN_LIGHT': (W - 20, 62), 'STALL_LIGHT': (W - 20, 78)}
jacks_in = {'A_IN': (30, 272), 'B_IN': (75, 272), 'RESET_IN': (120, 272), 'SEED_CV': (30, 340), 'MIX_CV': (75, 340)}
jacks_out = {'OUT': (120, 340)}
jack_labels = {'A_IN': 'A', 'B_IN': 'B', 'RESET_IN': 'RESET', 'SEED_CV': 'SEED', 'MIX_CV': 'MIX', 'OUT': 'OUT'}
p = frame(W) + [f'<rect x="98" y="316" width="42" height="52" rx="4" fill="{BLOCK}"/>']  # output block
p += [text('Séance', 14, 30, 20, OUT, 'start'), text('SPECTRAL FRAME', 14, 44, 7, LABEL, 'start')]
# III Boundary (commons or institution): the frame is a commons the row works inside.
p.append(glyph(3, W - 26, 22, 26, LABEL, ACCENT))
p += [text('CHAIN', W - 30, 65, 6, DIM, 'end'), text('STALL', W - 30, 81, 6, DIM, 'end')]
for y in (90, 242):
    p.append(f'<path d="M12 {y}H{W-12}" stroke="{RULE}"/>')
for name, (x, y, label) in knobs.items():
    p.append(text(label, x, y + 30, 8))
p.append(text('RESET', 110, 226, 8))
for name, (x, y) in {**jacks_in, **jacks_out}.items():
    p.append(text(jack_labels[name], x, y - 18, 7, OUT if name == 'OUT' else LABEL))
(root / 'res').mkdir(exist_ok=True)
(root / 'res/Seance.svg').write_text(''.join(p) + '</svg>')
emit('core', (('KNOB', knobs), ('BUTTON', buttons), ('LIGHT', lights), ('JACK', jacks_in), ('JACK', jacks_out)), W)


# ---------------------------------------------------------------- expanders (4 HP)
W = 60


def expander(file, ns, title, mark, meaning, knobs, switches, latches, jacks, legends=()):
    p = frame(W)
    p += [text('Séance', W / 2, 22, 7, DIM), text(title, W / 2, 38, 9, OUT)]
    p.append(f'<!-- {meaning} -->')
    p.append(glyph(mark, W / 2, 64, 24, LABEL, ACCENT))
    p.append(f'<path d="M8 84H{W-8}" stroke="{RULE}"/>')
    for name, (x, y, label) in knobs.items():
        p.append(text(label, x, y + 30, 7))
    for name, (x, y, label) in latches.items():
        p.append(text(label, x, y + 24, 7, ACCENT))
    for s, x, y, size, color, anchor in legends:
        p.append(text(s, x, y, size, color, anchor))
    for name, (x, y, label) in jacks.items():
        p.append(text(label, x, y - 18, 7))
    p.append(f'<circle cx="{W/2}" cy="350" r="5" fill="none" stroke="{RULE}"/>')
    p.append(text('LINK', W / 2, 366, 5.5, DIM))
    (root / f'res/{file}.svg').write_text(''.join(p) + '</svg>')
    lights = {'LINK_LIGHT': (W / 2, 350)}
    emit(ns, (('KNOB', knobs), ('SWITCH', switches), ('LATCH', latches), ('JACK', jacks), ('LIGHT', lights)), W)


# VI Regulation (returns to set point): the held frame.
expander('SeanceFreeze', 'freeze', 'FREEZE', 6, 'VI Regulation: returns to set point',
         knobs={'DRIFT': (30, 196, 'DRIFT')}, switches={}, latches={'FREEZE': (30, 120, 'FREEZE')},
         jacks={'GATE_IN': (30, 318, 'GATE')})
# XII Learned invariant (hard walls, one door): one seed, one scatter.
expander('SeanceScramble', 'scramble', 'SCRAMBLE', 12, 'XII Learned invariant: hard walls, one door',
         knobs={'RANGE': (30, 112, 'RANGE'), 'PHASE': (30, 180, 'PHASE'), 'HOLD': (30, 248, 'HOLD')}, switches={}, latches={},
         jacks={'RANGE_CV': (30, 318, 'RANGE')})
# IV Centre of decision (authority, contestable): B decides, DEPTH contests.
expander('SeanceCross', 'cross', 'CROSS', 4, 'IV Centre of decision: authority, contestable',
         knobs={'DEPTH': (30, 112, 'DEPTH'), 'SMOOTH': (30, 180, 'SMOOTH')}, switches={'MODE': (30, 248)}, latches={},
         jacks={'DEPTH_CV': (30, 318, 'DEPTH')},
         legends=(('MORPH', 36, 243, 5.5, LABEL, 'start'), ('MULT', 36, 257, 5.5, LABEL, 'start')))
# V Bottleneck (fails the bypass test): bins past the edge do not get through.
expander('SeanceWipe', 'wipe', 'WIPE', 5, 'V Bottleneck: fails the bypass test',
         knobs={'WIPE': (30, 112, 'WIPE'), 'SOFT': (30, 180, 'SOFT')}, switches={}, latches={},
         jacks={'WIPE_CV': (30, 318, 'WIPE')})

# ---------------------------------------------------------------- Bridge (8 HP)
W = 120
knobs = {'THRESHOLD': (32, 116, 'THRESH'), 'HYSTERESIS': (88, 116, 'HYST'),
         'SLEW': (60, 194, 'SLEW')}
jacks = {'BUS_IN': (32, 317, 'MASK IN'), 'BUS_OUT': (88, 317, 'ACT OUT')}
lights = {'LINK_LIGHT': (60, 350), **{f'BIT{b}_LIGHT': (18 + b * 12, 252) for b in range(8)}}
p = frame(W) + [text('Séance', 12, 27, 14, OUT, 'start'), text('BRIDGE', 12, 44, 9, LABEL, 'start')]
p.append(glyph(3, 96, 31, 24, LABEL, ACCENT))
p.append(f'<path d="M8 84H{W-8}" stroke="{RULE}"/>')
for x, y, label in knobs.values():
    p.append(text(label, x, y + 30, 8))
p += [text('dBFS', 32, 160, 6, DIM), text('dB', 88, 160, 6, DIM), text('ms', 60, 238, 6, DIM)]
for b in range(8):
    p.append(text(str(b), 18 + b * 12, 267, 6, DIM))
p += [text('LOW', 10, 280, 5.5, DIM, 'start'), text('ACTIVITY', 60, 280, 6, LABEL), text('HIGH', 110, 280, 5.5, DIM, 'end')]
p.append(f'<rect x="69" y="285" width="38" height="49" rx="4" fill="{BLOCK}"/>')
for x, y, label in jacks.values():
    p.append(text(label, x, y - 18, 7, OUT if label == 'ACT OUT' else LABEL))
p.append(text('LINK', 60, 366, 5.5, DIM))
(root / 'res/SeanceBridge.svg').write_text(''.join(p) + '</svg>')
emit('bridge', (('KNOB', knobs), ('JACK', jacks), ('LIGHT', lights)), W)

header.append('} // namespace seance_layout')
header.append('')
(root / 'src/Layout.hpp').write_text('\n'.join(header))
print('Wrote res/Seance.svg, res/SeanceFreeze.svg, res/SeanceScramble.svg, res/SeanceCross.svg, res/SeanceWipe.svg, res/SeanceBridge.svg and src/Layout.hpp')
